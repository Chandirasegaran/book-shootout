const STEP = 37; // coprime with the list length, so neighbouring pages never repeat

/** Scribble for the spread opened at odd `page`. It's written on the left page, `page - 1`. */
export function jokeFor(page) {
  const n = JOKES.length;
  const k = Math.floor((page - 1) / 2);
  return JOKES[((k * STEP) % n + n) % n].replaceAll("{page}", String(page - 1));
}

